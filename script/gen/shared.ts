/**
 * Shared helpers for the reference-catalog generators. All parsing is static
 * source analysis so generated output is deterministic and never depends on
 * runtime state.
 */

import path from "node:path"
import { mkdir, readFile } from "node:fs/promises"

export const REPO_ROOT = path.resolve(import.meta.dir, "../..")

export function banner(generator: string): string {
  return `<!-- GENERATED BY ${generator} — DO NOT EDIT BY HAND. Run \`bun script/gen/${generator}\` to regenerate. -->`
}

export async function writeGenerated(file: string, generator: string, body: string): Promise<void> {
  const content = `${banner(generator)}\n\n${body.trimEnd()}\n`
  await mkdir(path.dirname(file), { recursive: true })
  await Bun.write(file, content)
}

export async function isFresh(file: string, generator: string, body: string): Promise<boolean> {
  const expected = `${banner(generator)}\n\n${body.trimEnd()}\n`
  const current = await readFile(file, "utf8").catch(() => null)
  return current === expected
}

export function stringLiteral(text: string): string | null {
  const trimmed = text.trim()
  if (trimmed.length < 2) return null
  const quote = trimmed[0]
  if (quote !== '"' && quote !== "'" && quote !== "`") return null
  let result = ""
  for (let i = 1; i < trimmed.length; i++) {
    const c = trimmed[i]
    if (c === "\\") {
      const next = trimmed[i + 1]
      if (next === quote) {
        result += quote
        i++
      } else if (next === "\\") {
        result += "\\"
        i++
      } else if (next === "n") {
        result += " "
        i++
      } else {
        result += c
      }
      continue
    }
    if (c === quote) return result
    if (c === "\n") {
      result += " "
      continue
    }
    result += c
  }
  return null
}

export function templateLiteral(source: string, openIndex: number): string | null {
  let i = openIndex + 1
  let result = ""
  while (i < source.length) {
    const c = source[i]
    if (c === "\\") {
      const next = source[i + 1]
      if (next === "`" || next === "\\") {
        result += next
        i += 2
        continue
      }
      result += c
      i++
      continue
    }
    if (c === "`") return result
    if (c === "\n") {
      result += " "
      i++
      continue
    }
    result += c
    i++
  }
  return null
}

export function matchClose(source: string, openIndex: number, open = "{", close = "}"): number {
  let depth = 0
  let inString: "'" | '"' | null = null
  let inTemplate = false
  let inLineComment = false
  let inBlockComment = false
  for (let i = openIndex; i < source.length; i++) {
    const c = source[i]
    const prev = i > 0 ? source[i - 1] : ""
    if (inLineComment) {
      if (c === "\n") inLineComment = false
      continue
    }
    if (inBlockComment) {
      if (c === "/" && prev === "*") inBlockComment = false
      continue
    }
    if (inTemplate) {
      if (c === "`" && prev !== "\\") inTemplate = false
      continue
    }
    if (inString) {
      if (c === inString && prev !== "\\") inString = null
      continue
    }
    if (c === "/" && source[i + 1] === "/") {
      inLineComment = true
      continue
    }
    if (c === "/" && source[i + 1] === "*") {
      inBlockComment = true
      continue
    }
    if (c === "'" || c === '"') {
      inString = c
      continue
    }
    if (c === "`") {
      inTemplate = true
      continue
    }
    if (c === open) depth++
    else if (c === close) {
      depth--
      if (depth === 0) return i
    }
  }
  return -1
}

export function findBlock(source: string, marker: string, open = "{", close = "}"): string | null {
  const markerIndex = source.indexOf(marker)
  if (markerIndex < 0) return null
  const openIndex = source.indexOf(open, markerIndex + marker.length)
  if (openIndex < 0) return null
  const closeIndex = matchClose(source, openIndex, open, close)
  if (closeIndex < 0) return null
  return source.slice(openIndex + 1, closeIndex)
}

export function findAssign(source: string, key: string): string | null {
  const quoted = source.match(new RegExp(`${key}\\s*:\\s*("[^"]*"|'[^']*')`))
  if (quoted) return stringLiteral(quoted[1]!)
  const template = source.match(new RegExp(`${key}\\s*:\\s*\``))
  if (template) return templateLiteral(source, template.index! + template[0]!.length - 1)
  return null
}

export function resolveIdentifier(source: string, identifier: string): string | null {
  const match = source.match(new RegExp(`const\\s+${identifier}\\s*=\\s*[\n\r]?\\s*(["\`'])`))
  if (!match) return null
  const quote = match[1]!
  const openIndex = match.index! + match[0]!.length - 1
  if (quote === "`") return templateLiteral(source, openIndex)
  const rest = source.slice(openIndex)
  const closing = rest.indexOf(quote, 1)
  if (closing < 0) return null
  return stringLiteral(rest.slice(0, closing + 1))
}

export function zodTypeOf(expr: string): string | null {
  const trimmed = expr.trim()
  const enumMatch = trimmed.match(/z\s*\.\s*enum\s*\(\s*\[([^\]]*)\]/)
  if (enumMatch) {
    const values = enumMatch[1]!
      .split(",")
      .map((part) => stringLiteral(part))
      .filter((value): value is string => value !== null)
    if (values.length > 0) return values.map((value) => `"${value}"`).join(" | ")
    return "enum"
  }
  const object = trimmed.match(/z\s*\.\s*(strictObject|object)\s*\(/)
  if (object) return "object"
  const simple = trimmed.match(
    /z\s*\.\s*(string|number|boolean|bigint|date|literal|lazy|never|any|unknown|void|null|undefined)\s*\(/,
  )
  if (simple) return simple[1]!
  const array = trimmed.match(/z\s*\.\s*array\s*\(/)
  if (array) return "array"
  const record = trimmed.match(/z\s*\.\s*record\s*\(/)
  if (record) return "record"
  const union = trimmed.match(/z\s*\.\s*(union|discriminatedUnion)\s*\(/)
  if (union) return "union"
  const intersection = trimmed.match(/z\s*\.\s*(intersection|and)\s*\(/)
  if (intersection) return "intersection"
  const tuple = trimmed.match(/z\s*\.\s*tuple\s*\(/)
  if (tuple) return "tuple"
  const effect = trimmed.match(/z\s*\.\s*(custom|instanceof|function|promise|map|set)\s*\(/)
  if (effect) return effect[1]!
  const identifier = trimmed.match(/^([A-Za-z_][A-Za-z0-9_.]*)/)
  if (identifier) return identifier[1]!
  return null
}

export function inlineDescribe(expr: string): string | null {
  const marker = expr.lastIndexOf(".describe(")
  if (marker < 0) return null
  const openIndex = expr.indexOf("(", marker)
  const closeIndex = matchClose(expr, openIndex, "(", ")")
  if (closeIndex < 0) return null
  const arg = expr.slice(openIndex + 1, closeIndex)
  const parts = [...arg.matchAll(/("(?:\\.|[^"])*"|'(?:\\.|[^'])*'|`(?:\\.|[^`])*`)/g)]
    .map((match) => stringLiteral(match[1]!))
    .filter((value): value is string => value !== null)
  return parts.length > 0 ? parts.join("") : null
}

export function isOptionalExpr(expr: string): boolean {
  return /\.optional\(\)/.test(expr) || /\.default\(/.test(expr) || /\.optional\s*$/.test(expr)
}

export interface ObjectField {
  name: string
  expr: string
  description: string | null
  type: string | null
  optional: boolean
}

function balanced(expr: string): boolean {
  let depth = 0
  let inString: "'" | '"' | "`" | null = null
  for (let i = 0; i < expr.length; i++) {
    const c = expr[i]
    if (inString) {
      if (c === inString && expr[i - 1] !== "\\") inString = null
      continue
    }
    if (c === "'" || c === '"' || c === "`") {
      inString = c
      continue
    }
    if (c === "(" || c === "{" || c === "[") depth++
    else if (c === ")" || c === "}" || c === "]") depth--
  }
  return depth <= 0 && inString === null
}

export function parseObjectFields(block: string): ObjectField[] {
  const fields: ObjectField[] = []
  const lines = block.split("\n")
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!
    const match = line.match(/^\s*([A-Za-z_$][A-Za-z0-9_$]*)\s*:\s*(.+)$/)
    if (!match) continue
    const name = match[1]!
    let expr = match[2]!.trim()
    if (expr === "z" || expr.endsWith(".")) {
      let j = i + 1
      while (j < lines.length && j - i < 30) {
        const nextLine = lines[j]!
        expr += " " + nextLine.trim()
        if (balanced(expr) && nextLine.trim().endsWith(",")) break
        j++
      }
    }
    if (expr.endsWith(",")) expr = expr.slice(0, -1)
    const description = inlineDescribe(expr)
    fields.push({ name, expr, description, type: zodTypeOf(expr), optional: isOptionalExpr(expr) })
  }
  return fields
}

export function firstStringArg(source: string, after: string): string | null {
  const index = source.indexOf(after)
  if (index < 0) return null
  const paren = source.indexOf("(", index + after.length)
  if (paren < 0) return null
  const rest = source.slice(paren + 1)
  const match = rest.match(/^\s*("[^"]*"|'[^']*')/)
  return match ? stringLiteral(match[1]!) : null
}

export function mdCell(text: string): string {
  return text.replace(/\|/g, "\\|")
}
