import path from "node:path"
import { ComponentFeatures, FeatureSelection, type FeatureComponent } from "../../packages/util/src/features"

const root = path.resolve(import.meta.dirname, "../..")
const check = process.argv.includes("--check")
const catalog: FeatureComponent[] = []
for (const filename of await Array.fromAsync(new Bun.Glob("packages/*/package.json").scan({ cwd: root }))) {
  const file = Bun.file(path.join(root, filename))
  const manifest = await file.json()
  if (manifest.synergy?.kind !== "component") continue
  const source = path.join(root, path.dirname(filename), "src/features.ts")
  const definitions = await import(source)
  const features = ComponentFeatures.parse(definitions.componentFeatures)
  catalog.push({ ...manifest.synergy, features })
  if (JSON.stringify(manifest.synergy.features) === JSON.stringify(features)) continue
  if (check) throw new Error(`Stale generated feature metadata: ${filename}; run bun script/gen/gen-feature-catalog.ts`)
  manifest.synergy.features = features
  await Bun.write(file, JSON.stringify(manifest, null, 2) + "\n")
}
FeatureSelection.resolve(catalog, { provided: { "local-runtime": "local", "plugin-host": "local" } })
const copy = Object.fromEntries(
  catalog.flatMap(
    (component) =>
      component.features?.definitions.map((feature) => [
        feature.id,
        {
          name: { id: `features.${feature.id}.name`, message: feature.name },
          description: { id: `features.${feature.id}.description`, message: feature.description },
        },
      ]) ?? [],
  ),
)
const copyFile = Bun.file(path.join(root, "apps/web/src/components/settings/feature-copy.ts"))
const { format } = await import("prettier")
const source = await format(
  `// Generated by script/gen/gen-feature-catalog.ts.\nimport type { MessageDescriptor } from "@lingui/core"\nexport const featureCopy: Record<string, { name: MessageDescriptor; description: MessageDescriptor }> = ${JSON.stringify(copy, null, 2)}\n`,
  { parser: "typescript", semi: false, printWidth: 110 },
)
if (check) {
  if (!(await copyFile.exists()) || (await copyFile.text()) !== source)
    throw new Error("Stale generated feature translations")
} else await Bun.write(copyFile, source)
console.log(`Validated ${catalog.length} component feature declarations`)
